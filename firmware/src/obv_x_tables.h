static inline uint32_t opera_x_wt_band(uint32_t inc)
{
    /* Band-limited table choice based on actual oscillator Q32 increment.
     * All tables share the same sampling grid and have seamless wrap. */
    if (inc < 63293885u) return 0u;  /* ~650Hz: <=32 partials */
    if (inc < 121739163u) return 1u; /* ~1250Hz: <=16 partials */
    if (inc < 243478326u) return 2u; /* ~2500Hz: <=8 partials */
    if (inc < 486956652u) return 3u; /* ~5000Hz: <=4 partials */
    return 4u; /* <=2 partials */
}
/* 0..127 maps to 5 different stages at 0/32/64/96/127. For each sample,
 * only two neighboring stages are interpolated; no five-way weighted sum.
 * The final endpoint is exact: at 127, stage3:stage4 blend = 0:128. */
static inline uint32_t opera_x_wt_stage(uint8_t morph)
{
    return morph >> 5; /* 0..3 */
}
static inline uint32_t opera_x_wt_blend(uint8_t morph)
{
    return morph == 127u ? 128u : (uint32_t)(morph & 31u) << 2;
}
static inline int32_t opera_x_wt_lookup(uint32_t ph, uint32_t inc, uint32_t morph, uint32_t family)
{
    uint32_t i = ph >> 24, band = opera_x_wt_band(inc);
    uint32_t frac = (ph >> 16) & 255u;
    uint8_t pos = (uint8_t)(morph > 127u ? 127u : morph);
    uint32_t stage = opera_x_wt_stage(pos), blend = opera_x_wt_blend(pos);
    const int16_t *a = opera_x_spectra[family & 1u][stage][band];
    const int16_t *b = opera_x_spectra[family & 1u][stage + 1u][band];
    int32_t y0 = a[i] + (((int32_t)(a[i + 1u] - a[i]) * (int32_t)frac) >> 8);
    int32_t y1 = b[i] + (((int32_t)(b[i + 1u] - b[i]) * (int32_t)frac) >> 8);
    return y0 + (((y1 - y0) * (int32_t)blend) >> 7);
}
static inline int32_t opera_x_wt_step(osc_t *o, uint32_t inc, uint32_t morph, uint32_t family, int32_t reset_t)
{
    int32_t out = o->prev;
    o->ph = reset_t < 0 ? o->ph + inc : (inc >> 15) * (uint32_t)reset_t;
    o->prev = opera_x_wt_lookup(o->ph, inc, morph, family);
    return out;
}
